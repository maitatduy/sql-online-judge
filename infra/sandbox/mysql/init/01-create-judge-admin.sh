#!/bin/bash
set -eu

mysql --protocol=socket -uroot -p"${MYSQL_ROOT_PASSWORD}" <<-SQL
    CREATE USER '${SANDBOX_MYSQL_ADMIN_USER}'@'%' IDENTIFIED BY '${SANDBOX_MYSQL_ADMIN_PASSWORD}';
    GRANT CREATE USER, PROCESS, CONNECTION_ADMIN ON *.* TO '${SANDBOX_MYSQL_ADMIN_USER}'@'%';
    GRANT ALL PRIVILEGES ON \`sb\_%\`.* TO '${SANDBOX_MYSQL_ADMIN_USER}'@'%' WITH GRANT OPTION;
    FLUSH PRIVILEGES;
SQL
