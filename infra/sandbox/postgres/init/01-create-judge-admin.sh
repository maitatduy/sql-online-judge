#!/bin/bash
set -eu

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "${POSTGRES_DB}" <<-SQL
    CREATE ROLE ${SANDBOX_PG_ADMIN_USER} LOGIN CREATEROLE PASSWORD '${SANDBOX_PG_ADMIN_PASSWORD}';
    GRANT pg_signal_backend TO ${SANDBOX_PG_ADMIN_USER};
    GRANT CREATE ON DATABASE ${POSTGRES_DB} TO ${SANDBOX_PG_ADMIN_USER};
    REVOKE TEMPORARY ON DATABASE ${POSTGRES_DB} FROM PUBLIC;
    REVOKE ALL ON SCHEMA public FROM PUBLIC;
SQL
